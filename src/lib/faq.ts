export function getFaqLinkForPath(pathname: string) {
  const sectionId = faqSectionByPath[pathname];
  if (!sectionId) return null;
  return `/faq#${sectionId}`;
}

export function getFaqLabelForPath(pathname: string) {
  const sectionId = faqSectionByPath[pathname];
  if (!sectionId) return "";
  const section = faqSections.find((item) => item.id === sectionId);
  return section?.title || "";
}
